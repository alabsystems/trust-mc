//! Kani function classification enums.
//!
//! There are three categories of special Kani functions:
//!    1. **Intrinsics**: MIR bodies generated during compilation (require type knowledge).
//!    2. **Models**: Functions modeling specific runtime behavior for Kani instrumentation.
//!    3. **Hooks**: Backend-specific logic generated during codegen.
//!
//! These functions are marked with `kanitool::fn_marker` attributes. The marker
//! value contains "Intrinsic", "Model", or "Hook" suffix indicating category.
//!
//! Extracted from `trust_mc-compiler/src/kani_middle/kani_functions.rs` (Part of #2997).

use std::str::FromStr;
use strum_macros::{EnumIter, EnumString, IntoStaticStr};

#[derive(Debug, Copy, Clone, Eq, PartialEq, Hash)]
pub enum KaniFunction {
    Model(KaniModel),
    Intrinsic(KaniIntrinsic),
    Hook(KaniHook),
}

/// Kani intrinsics are functions generated by the compiler.
///
/// These functions usually depend on information that require extra knowledge about the type
/// or extra Kani instrumentation.
#[derive(Debug, Copy, Clone, Eq, PartialEq, IntoStaticStr, EnumIter, EnumString, Hash)]
pub enum KaniIntrinsic {
    #[strum(serialize = "AnyModifiesIntrinsic")]
    AnyModifies,
    #[strum(serialize = "CheckedAlignOfIntrinsic")]
    CheckedAlignOf,
    #[strum(serialize = "CheckedSizeOfIntrinsic")]
    CheckedSizeOf,
    #[strum(serialize = "AutomaticHarnessIntrinsic")]
    AutomaticHarness,
    /// Checks if a float value can be converted to an integer without overflow.
    /// Returns true if the value after truncation is in range of the target Int type.
    /// Part of #1369: Converted from hook to intrinsic for uniform semantics.
    #[strum(serialize = "FloatToIntInRangeIntrinsic")]
    FloatToIntInRange,
    #[strum(serialize = "IsInitializedIntrinsic")]
    IsInitialized,
    #[strum(serialize = "ValidValueIntrinsic")]
    ValidValue,
    #[strum(serialize = "WriteAnyIntrinsic")]
    WriteAny,
}

